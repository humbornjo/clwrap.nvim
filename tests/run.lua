test("editorconfig and virt-column widths resolve per buffer", function()
  local previous = package.loaded["virt-column.config"]
  package.loaded["virt-column.config"] = {
    get_config = function()
      return { virtcolumn = "+1,75" }
    end,
  }
  local bufnr = make_buffer("go", "package p\n")
  vim.bo[bufnr].textwidth = 120
  vim.b[bufnr].editorconfig = { max_line_length = "110" }
  local resolved = config.resolve(bufnr)
  eq(110, resolved.comment_width)
  eq(75, resolved.doc_width)

  vim.b[bufnr].editorconfig = {}
  resolved = config.resolve(bufnr)
  eq(121, resolved.comment_width)
  eq(75, resolved.doc_width)

  vim.b[bufnr].clwrap_comment_width = 90
  vim.b[bufnr].clwrap_doc_width = 70
  resolved = config.resolve(bufnr)
  eq(90, resolved.comment_width)
  eq(70, resolved.doc_width)
  package.loaded["virt-column.config"] = previous
end)

