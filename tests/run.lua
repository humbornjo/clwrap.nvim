test("batch formats below Neovim's cwd and ignores dependency directories", function()
  local root = vim.fn.tempname()
  vim.fn.mkdir(vim.fs.joinpath(root, "nested"), "p")
  vim.fn.mkdir(vim.fs.joinpath(root, "node_modules"), "p")
  local function write(path, source)
    vim.fn.writefile(vim.split(source, "\n", { plain = true, trimempty = true }), path)
  end
  local function read(path)
    return table.concat(vim.fn.readfile(path), "\n") .. "\n"
  end

  write(vim.fs.joinpath(root, "main.go"), go_cases[1].src)
  write(vim.fs.joinpath(root, "nested", "other.go"), go_cases[1].src)
  write(vim.fs.joinpath(root, "nested", "other.lua"), lua_cases[1].src)
  write(vim.fs.joinpath(root, "node_modules", "ignored.go"), go_cases[1].src)
  write(vim.fs.joinpath(root, "notes.txt"), go_cases[1].src)

  local previous_cwd = vim.fn.getcwd()
  vim.api.nvim_set_current_dir(root)
  local report = clwrap.format_all(nil, {
    doc_width = 60,
    comment_width = 100,
    editorconfig = false,
    virtcolumn = false,
  })
  vim.api.nvim_set_current_dir(previous_cwd)
  eq(3, #report.formatted)
  eq(0, #report.errors)
  eq(go_cases[1].want, read(vim.fs.joinpath(root, "main.go")))
  eq(go_cases[1].want, read(vim.fs.joinpath(root, "nested", "other.go")))
  eq(lua_cases[1].want, read(vim.fs.joinpath(root, "nested", "other.lua")))
  eq(go_cases[1].src, read(vim.fs.joinpath(root, "node_modules", "ignored.go")))

  report = clwrap.format_all(root, { doc_width = 60, comment_width = 100, editorconfig = false, virtcolumn = false })
  eq(3, #report.unchanged)
  eq(0, #report.formatted)
end)

test("batch skips modified buffers without saving unrelated edits", function()
  local root = vim.fn.tempname()
  vim.fn.mkdir(root, "p")
  local path = vim.fs.joinpath(root, "main.go")
  vim.fn.writefile({ "package p" }, path)
  local bufnr = vim.fn.bufadd(path)
  buffers[#buffers + 1] = bufnr
  vim.fn.bufload(bufnr)
  vim.api.nvim_buf_set_lines(bufnr, 0, -1, false, { "// unsaved local edit", "package p" })

  local report = clwrap.format_all(root)
  eq(1, #report.skipped)
  eq(0, #report.formatted)
  eq({ "package p" }, vim.fn.readfile(path))
  eq(true, vim.bo[bufnr].modified)
  eq("// unsaved local edit", vim.api.nvim_buf_get_lines(bufnr, 0, 1, false)[1])
end)

test("format_on_save honors global and buffer-local settings", function()
  local path = vim.fn.tempname() .. ".go"
  local bufnr = vim.fn.bufadd(path)
  buffers[#buffers + 1] = bufnr
  vim.fn.bufload(bufnr)
  vim.bo[bufnr].filetype = "go"
  vim.b[bufnr].clwrap_doc_width = 60
  vim.b[bufnr].clwrap_comment_width = 100

  clwrap.setup({ format_on_save = true })
  vim.api.nvim_buf_set_lines(bufnr, 0, -1, false, vim.split(go_cases[1].src, "\n", { plain = true, trimempty = true }))
  vim.api.nvim_buf_call(bufnr, function()
    vim.cmd("silent write")
  end)
  eq(go_cases[1].want, table.concat(vim.fn.readfile(path), "\n") .. "\n")

  vim.b[bufnr].clwrap_format_on_save = false
  vim.api.nvim_buf_set_lines(bufnr, 0, -1, false, vim.split(go_cases[1].src, "\n", { plain = true, trimempty = true }))
  vim.api.nvim_buf_call(bufnr, function()
    vim.cmd("silent write")
  end)
  eq(go_cases[1].src, table.concat(vim.fn.readfile(path), "\n") .. "\n")

  clwrap.setup({ format_on_save = false })
  vim.b[bufnr].clwrap_format_on_save = nil
  vim.api.nvim_buf_set_lines(bufnr, 0, -1, false, vim.split(go_cases[1].src, "\n", { plain = true, trimempty = true }))
  vim.api.nvim_buf_call(bufnr, function()
    vim.cmd("silent write")
  end)
  eq(go_cases[1].src, table.concat(vim.fn.readfile(path), "\n") .. "\n")
end)

for _, case in ipairs(tests) do
  buffers = {}
  local ok, err = pcall(case.fn)
  for _, bufnr in ipairs(buffers) do
    if vim.api.nvim_buf_is_valid(bufnr) then
      vim.api.nvim_buf_delete(bufnr, { force = true })
    end
  end
  if ok then
    passed = passed + 1
    print("PASS " .. case.name)
  else
    failed = failed + 1
    print("FAIL " .. case.name .. "\n" .. tostring(err))
  end
end

print(("clwrap: %d passed, %d failed, %d skipped"):format(passed, failed, skipped))
if failed > 0 then
  error("test suite failed")
end
