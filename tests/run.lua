local clwrap = require("clwrap")
local config = require("clwrap.config")

local tests = {}
local buffers = {}
local passed, failed, skipped = 0, 0, 0

local function test(name, fn)
  tests[#tests + 1] = { name = name, fn = fn }
end

local function eq(expected, actual)
  if not vim.deep_equal(expected, actual) then
    error(("expected:\n%s\nactual:\n%s"):format(vim.inspect(expected), vim.inspect(actual)), 2)
  end
end

local function make_buffer(lang, source, filetype)
  local bufnr = vim.api.nvim_create_buf(true, false)
  buffers[#buffers + 1] = bufnr
  vim.api.nvim_buf_set_name(bufnr, vim.fn.tempname() .. "." .. lang)
  vim.api.nvim_buf_set_lines(bufnr, 0, -1, false, vim.split(source, "\n", { plain = true }))
  vim.bo[bufnr].tabstop = 2
  vim.bo[bufnr].filetype = filetype or lang
  return bufnr
end

local default_opts = {
  doc_width = 60,
  comment_width = 100,
  tolerance = 2,
  editorconfig = false,
  virtcolumn = false,
}

local function reflow(lang, source, opts)
  local bufnr = make_buffer(lang, source, lang == "tsx" and "typescriptreact" or nil)
  local changed, err = clwrap.format(bufnr, opts or default_opts)
  assert(changed ~= nil, err)
  local result = table.concat(vim.api.nvim_buf_get_lines(bufnr, 0, -1, false), "\n")
  local again, again_err = clwrap.format(bufnr, opts or default_opts)
  assert(again ~= nil, again_err)
  eq(result, table.concat(vim.api.nvim_buf_get_lines(bufnr, 0, -1, false), "\n"))
  return result
end

