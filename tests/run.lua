test("go: syntax errors leave the buffer unchanged", function()
  local bufnr = make_buffer("go", "package p\nfunc broken( {\n")
  local before = vim.api.nvim_buf_get_lines(bufnr, 0, -1, false)
  local changed, err = clwrap.format(bufnr, default_opts)
  eq(nil, changed)
  assert(err:match("syntax errors"), err)
  eq(before, vim.api.nvim_buf_get_lines(bufnr, 0, -1, false))
end)

test("go: configurable prefix exemptions", function()
  local src =
    "package p\n\n// Run demonstrates configurable prefix exemptions.\n//\n// > quoted text keeps\n// > its original layout.\nfunc Run() {}\n"
  local opts = vim.tbl_extend("force", {}, default_opts, { exempted_prefixes = { " ", "\t", "- ", "* ", "+ ", "> " } })
  eq(src, reflow("go", src, opts))
end)

